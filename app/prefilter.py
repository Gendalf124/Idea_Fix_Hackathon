"""Быстрый фильтр до ИИ: стоит ли вообще отправлять сообщение на разбор.

Цель — не пропустить ни одной из реальных формулировок школьного чата и при этом не тратить токены на болтовню.
Фильтр намеренно «щедрый»: сомнительное сообщение уходит ИИ, а он решает, есть ли в нём задание.
Всё разложено по группам, чтобы было видно, что и зачем ищется. Новые слова добавляются в нужную группу.

Группы:
  STRONG   — слова, по которым ясно, что речь о задании, даже если сообщение короткое («ДЗ», «Задали»);
  WORK     — что делать: выучить, решить, принести, подготовить, нарисовать…
  PLACES   — где: параграф, страница, номер, упражнение, учебник, тетрадь…
  WORKS    — виды работ: доклад, реферат, проект, сочинение, диктант…
  CONTROL  — контрольные и проверки: контрольная, к/р, с/р, тест, ВПР, ОГЭ, ЕГЭ…
  LESSON   — что проходили на уроке;
  DEADLINE — сроки: до завтра, к пятнице, до 15.11, к следующему уроку…
  SUBJECTS — предметы и их сокращения.
"""
import re

FLAGS = re.IGNORECASE


def _rx(*parts: str):
    return re.compile("|".join(parts), FLAGS)


STRONG = _rx(
    r"\bдз\b", r"\bд/з\b", r"\bд\.\s?з\b", r"домашк", r"домашн", r"дом\.?\s?зад", r"дом\.?\s?работ",
    r"\bзадан", r"\bзадал", r"\bзадач", r"на дом\b",
)

WORK = _rx(
    r"выуч", r"учить\b", r"заучи", r"наизусть", r"прочита", r"прочесть", r"\bчитать\b", r"перечита",
    r"\bреши", r"решить", r"решайте", r"напиши", r"написать", r"сделать", r"сделайте", r"выполни",
    r"подготов", r"принест", r"принесите", r"взять с собой", r"повтор(ить|ите)\b", r"пересказ",
    r"списать", r"спишите", r"нарисо", r"начерти", r"составить", r"составьте", r"ответить на",
    r"ответьте на", r"найти\b", r"найдите", r"заполни", r"оформи", r"выписа", r"разобра(ть|ться)\b",
    r"сдать", r"сдайте", r"сдаём", r"сдаем", r"сдавать", r"сдача", r"скинуть", r"отправить учителю",
)

PLACES = _rx(
    r"параграф", r"§", r"\bпар\.\s?\d", r"\bглав[аыу]\b", r"страниц", r"\bстр\.?\s?\d", r"\bс\.\s?\d",
    r"№", r"\bномер", r"\bупр\.?\s?\d", r"упражн", r"учебник", r"тетрад", r"рабочая тетрадь", r"\bпример[ыа]?\b",
    r"\bвопрос", r"\bтаблиц", r"\bконспект", r"\bтекст\b", r"\bстих", r"\bтема\b", r"\bтемы\b", r"\bтему\b",
)

WORKS = _rx(
    r"доклад", r"реферат", r"проект", r"сочинени", r"изложени", r"диктант", r"презентаци", r"кроссворд",
    r"поделк", r"чертёж", r"чертеж", r"рисунок", r"плакат", r"модель", r"макет", r"гербарий", r"отчёт", r"отчет",
    r"лабораторн", r"практическ", r"словарн", r"эссе", r"мини-?проект",
)

CONTROL = _rx(
    r"контрольн", r"\bк/р\b", r"\bкр\b", r"самостоятельн", r"\bс/р\b", r"\bтест", r"зач[её]т", r"экзамен",
    r"\bогэ\b", r"\bегэ\b", r"\bвпр\b", r"проверочн", r"диагностическ", r"олимпиад", r"пробник", r"\bопрос\b",
    r"аттестаци", r"четвертн", r"итогов",
)

LESSON = _rx(
    r"проходили", r"прошли", r"проходим", r"изучали", r"изучаем", r"разобрали", r"на уроке", r"на прошлом уроке",
    r"на последнем уроке", r"к уроку", r"к следующему уроку", r"на след(ующий|\.)? ?урок", r"на следующем уроке",
)

_DAYS = r"(пон|вт|ср[еу]|чет|пят|суб|вос)"
_MONTHS = r"(январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)"
DEADLINE = _rx(
    r"на завтра", r"до завтра", r"к завтра", r"послезавтра", r"на сегодня", r"до сегодня",
    r"завтра\s+(сдаём|сдаем|сдать|сдавать|принести|принесите|будет|контрольн|тест|проверочн|самостоятельн|нужно|надо)",
    r"сегодня\s+(задали|задано|надо|нужно)", r"до\s+" + _DAYS, r"к\s+" + _DAYS,
    r"до\s+\d{1,2}[./]\d{1,2}", r"до\s+\d{1,2}\s+" + _MONTHS, r"к\s+\d{1,2}\s+" + _MONTHS,
    r"до конца (недели|четверти|месяца|года)", r"крайний срок", r"срок сдачи", r"дедлайн", r"в срок\b",
)

SUBJECTS = _rx(
    r"алгебр", r"геометр", r"математик", r"\bматем\b", r"вероятност\w* и статистик", r"русск\w*", r"\bрус\.?\s?яз",
    r"литератур", r"\bлит-ра\b", r"родн\w* (язык|литератур)", r"физик", r"хими", r"биолог", r"географ",
    r"истори", r"обществ", r"окружающ\w* мир", r"информатик", r"англ\w*", r"немецк", r"француз", r"башкир",
    r"татарск", r"технолог", r"\bтруд\b", r"\bобж\b", r"\bобзр\b", r"музык", r"\bизо\b", r"рисован",
    r"черчени", r"астроном", r"\bмхк\b", r"основы (безопасности|духовно)", r"одкнр", r"\bорксэ\b", r"физкульт",
    r"физическ\w* культур", r"\bфизра\b",
)

GROUPS = (STRONG, WORK, PLACES, WORKS, CONTROL, LESSON, DEADLINE, SUBJECTS)

MIN_LEN = 5          # короче — только если есть «сильное» слово (ДЗ, задали…)
STRONG_MIN_LEN = 2


def looks_useful(text: str) -> bool:
    """True — сообщение стоит отправить ИИ."""
    text = (text or "").strip()
    if len(text) < STRONG_MIN_LEN:
        return False
    if STRONG.search(text):
        return True
    return len(text) >= MIN_LEN and any(group.search(text) for group in GROUPS)
