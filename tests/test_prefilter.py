class Prefilter(unittest.TestCase):
    def test_real_phrasings_pass(self):
        missed = [t for t in SHOULD_PASS if not looks_useful(t)]
        self.assertEqual(missed, [], f"фильтр пропустил бы задание: {missed}")

    def test_chatter_stops(self):
        leaked = [t for t in SHOULD_STOP if looks_useful(t)]
        self.assertEqual(leaked, [], f"болтовня ушла бы к ИИ: {leaked}")

    def test_every_group_works(self):
        for group in GROUPS:
            self.assertTrue(group.pattern)  # каждая группа непустая и компилируется

    def test_case_and_yo(self):
        self.assertTrue(looks_useful("ЗАДАЛИ ПАРАГРАФ"))
        self.assertTrue(looks_useful("зачёт по физике"))
        self.assertTrue(looks_useful("зачет по физике"))


